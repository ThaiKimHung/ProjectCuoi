// Generates src/theme.css: every Tailwind color the app uses becomes a CSS
// variable, so one place decides the palette.
//   :root        light theme (ivory + sage) — neutral and tinted scales are inverted
//                so classes written for the old dark UI read correctly on light.
//   .theme-dark  dark scope for photo viewers (Lightbox, Compare, annotation).
// Run: node client/scripts/gen-theme.cjs
const fs = require('fs');
const path = require('path');
const colors = require('../node_modules/tailwindcss/colors.js');

const STOPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const rgb = hex => {
  const n = parseInt(hex.replace('#', ''), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};

// Light ivory neutrals, indexed by the *old dark-UI* role of each stop:
// 950 page, 900 panel, 800 soft fill, 700 border, 400 secondary text, 100 main text.
const ivory = {
  50: '#1f1d1a', 100: '#2a2723', 200: '#36322d', 300: '#48433c', 400: '#68615a',
  500: '#746c60', 600: '#b3ab9e', 700: '#e3ddd2', 800: '#f1ece4', 900: '#ffffff', 950: '#faf8f4',
};
const sage = {
  50: '#f3f6f1', 100: '#e4ebe1', 200: '#c9d7c4', 300: '#a5bc9f', 400: '#7f9c79',
  500: '#5f7e5b', 600: '#4e6b4a', 700: '#40583d', 800: '#344832', 900: '#2a3a28', 950: '#1c271b',
};
// Old dark UI used light stops for text and dark stops for tinted backgrounds.
// On light, swap them; keep 500–700 (solid buttons with white text) as they are.
const invert = { 50: 900, 100: 800, 200: 800, 300: 700, 400: 700, 500: 500, 600: 600, 700: 700, 800: 200, 900: 100, 950: 50 };
const tinted = ['emerald', 'amber', 'blue', 'purple', 'red', 'sky'];

const light = [];
const dark = [];
const add = (list, name, ramp) => STOPS.forEach(s => list.push(`  --c-${name}-${s}: ${rgb(ramp[s])};`));

add(light, 'slate', ivory);
add(light, 'stone', ivory);
add(light, 'rose', Object.fromEntries(STOPS.map(s => [s, sage[invert[s]]])));
tinted.forEach(name => add(light, name, Object.fromEntries(STOPS.map(s => [s, colors[name][invert[s]]]))));
light.push(`  --c-white: ${rgb('#1f1d1a')};`);

add(dark, 'slate', colors.slate);
add(dark, 'stone', colors.stone);
add(dark, 'rose', sage);
tinted.forEach(name => add(dark, name, colors[name]));
dark.push(`  --c-white: ${rgb('#ffffff')};`);

const css = `/* Generated by client/scripts/gen-theme.cjs — edit the script, not this file. */
:root {
${light.join('\n')}
  --studio-bg: #faf8f4;
  --studio-panel: #ffffff;
  --studio-raised: #f4f0e9;
  --studio-line: #e3ddd2;
  --studio-line-strong: #cfc7b9;
  --studio-text: #2a2723;
  --studio-muted: #68615a;
  --studio-accent: #5f7e5b;
  --studio-accent-hover: #4e6b4a;
  --studio-accent-soft: #e4ebe1;
  --studio-accent-ink: #ffffff;
  --studio-accent-text: #40583d;
  --studio-scroll: #cfc7b9;
  color-scheme: light;
}

.theme-dark {
${dark.join('\n')}
  --studio-bg: #121113;
  --studio-panel: #1b1a1d;
  --studio-raised: #242226;
  --studio-line: #333036;
  --studio-line-strong: #4a464e;
  --studio-text: #ece8e3;
  --studio-muted: #a29c95;
  --studio-accent: #8fae89;
  --studio-accent-hover: #a5bc9f;
  --studio-accent-soft: rgb(143 174 137 / 0.16);
  --studio-accent-ink: #13200f;
  --studio-accent-text: #b8cdb3;
  --studio-scroll: #4a464e;
  color-scheme: dark;
}
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'theme.css'), css);
console.log('wrote src/theme.css');
